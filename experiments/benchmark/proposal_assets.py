"""Table and numbers of the runs fixed in experiments/record/PLAN_2026-11-13.md.

    python experiments/benchmark/proposal_assets.py

Reads results/proposal/<name>_<expert>/ALL_summary.csv (made by run_proposal_experiments.sh),
copies the descriptive columns to paper/data/proposal_2026-11-13/ and writes
paper/tables/proposal.tex (rows of the table) and paper/tables/proposal_numbers.tex (macros).
The plan reports these runs as descriptive, so the p values of the summaries are left out.
"""
import os

import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = os.path.join(ROOT, "results", "proposal")
DATA = os.path.join(ROOT, "paper", "data", "proposal_2026-11-13")
TABLES = os.path.join(ROOT, "paper", "tables")
KEEP = ["strategy", "batch_size", "runs", "cases", "q_mean", "q_median", "certified_pct",
        "wrong_when_certified_pct", "wrong_ci95", "cases_no_question"]
RUNS = [("placebo", "Climate change", "Clim"), ("acidification", "Acidification", "Acid"),
        ("water_use", "Water use", "Water"), ("resource_use_fossils", "Resource use, fossils", "Fossil"),
        ("no_location", "No location", "NoLoc"), ("uniform", "Uniform priors", "Unif")]
STRATS = ["decision_flip", "sobol", "entropy", "random"]


def load(name, expert):
    df = pd.read_csv(os.path.join(SRC, f"{name}_{expert}", "ALL_summary.csv"))
    if not ((df.runs == 540) & (df.cases == 18) & (df.batch_size == 3)).all() or set(df.strategy) != set(STRATS):
        raise SystemExit(f"{name}_{expert}: incomplete run")
    os.makedirs(DATA, exist_ok=True)
    df[KEEP].to_csv(os.path.join(DATA, f"{name}_{expert}.csv"), index=False)
    return df.set_index("strategy")


def ci(text):
    lo, hi = text.split(" to ")
    return f"{float(lo):.1f}--{float(hi):.1f}"


def main():
    if not os.path.isdir(SRC):
        print("no results/proposal: keeping paper/tables/proposal.tex as committed")
        return
    rows, macros = [], []
    for name, label, tag in RUNS:
        p, t = load(name, "prior"), load(name, "tails")
        q = [f"{p.loc[s, 'q_mean']:.2f}" for s in STRATS]
        wp, wt = p.loc["decision_flip"], t.loc["decision_flip"]
        if (p.certified_pct < 100).any() or (t.certified_pct < 100).any():
            raise SystemExit(f"{name}: not every session certified; the table assumes it")
        rows.append(f"{label} & {int(wp.cases_no_question)} & " + " & ".join(q)
                    + f" & {wp.wrong_when_certified_pct:.1f} ({ci(wp.wrong_ci95)})"
                    + f" & {wt.wrong_when_certified_pct:.1f} ({ci(wt.wrong_ci95)}) \\\\")
        if name == "resource_use_fossils":
            rows.append("\\midrule")
        macros += [f"\\newcommand{{\\pq{tag}}}{{{p.loc['decision_flip', 'q_mean']:.2f}}}",
                   f"\\newcommand{{\\pqEnt{tag}}}{{{p.loc['entropy', 'q_mean']:.2f}}}",
                   f"\\newcommand{{\\pqRand{tag}}}{{{p.loc['random', 'q_mean']:.2f}}}",
                   f"\\newcommand{{\\pNoQ{tag}}}{{{int(wp.cases_no_question)}}}",
                   f"\\newcommand{{\\pw{tag}}}{{{wp.wrong_when_certified_pct:.1f}\\%}}",
                   f"\\newcommand{{\\pwTails{tag}}}{{{wt.wrong_when_certified_pct:.1f}\\%}}",
                   f"\\newcommand{{\\pwTailsCi{tag}}}{{{ci(wt.wrong_ci95)}\\%}}",
                   f"\\newcommand{{\\pwCi{tag}}}{{{ci(wp.wrong_ci95)}\\%}}"]
    with open(os.path.join(TABLES, "proposal.tex"), "w") as fh:
        fh.write("\n".join(rows) + "\n")
    with open(os.path.join(TABLES, "proposal_numbers.tex"), "w") as fh:
        fh.write("% generated by experiments/benchmark/proposal_assets.py\n" + "\n".join(macros) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
